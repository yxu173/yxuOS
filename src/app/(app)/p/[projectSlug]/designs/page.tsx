import { and, eq } from "drizzle-orm";

import { createDesign } from "@/app/(app)/designs/actions";
import { listDesignFoldersForProject } from "@/app/(app)/designs/folder-actions";
import { DesignFolderTree } from "@/components/design-folders/folder-tree";
import {
  buildDesignFolderTree,
  type DesignFolderTreeItem,
} from "@/components/design-folders/types";
import { Button } from "@/components/ui/button";
import { AppTopBar } from "@/components/workspaces/app-top-bar";
import { db } from "@/db";
import { designs } from "@/db/schema";
import { requireActiveProject } from "@/lib/permissions";
import { listProjectsForTeam } from "@/lib/projects";
import { listUserTeams } from "@/lib/teams";

interface PageProps {
  params: Promise<{ projectSlug: string }>;
}

export default async function ProjectDesignsIndexPage({
  params,
}: PageProps) {
  const { projectSlug } = await params;

  const { session, teamId, projectId, projectName } =
    await requireActiveProject(projectSlug);

  const [designRows, teams, projects, folderRows] = await Promise.all([
    db.query.designs.findMany({
      where: and(
        eq(designs.teamId, teamId),
        eq(designs.projectId, projectId),
      ),
      columns: {
        id: true,
        name: true,
        folderId: true,
        updatedAt: true,
      },
      with: {
        owner: {
          columns: {
            name: true,
            username: true,
            displayUsername: true,
          },
        },
      },
    }),
    listUserTeams(session.user.id),
    listProjectsForTeam(teamId),
    listDesignFoldersForProject(projectId),
  ]);

  const designEntries: Array<DesignFolderTreeItem & { folderId: string | null }> =
    designRows.map((row) => ({
      id: row.id,
      name: row.name,
      updatedAt: row.updatedAt,
      folderId: row.folderId,
      creator: row.owner
        ? {
            name: row.owner.name,
            username: row.owner.displayUsername ?? row.owner.username,
          }
        : null,
    }));

  const { roots, rootDesigns } = buildDesignFolderTree({
    folders: folderRows,
    designs: designEntries,
  });

  const flatFolders: Array<{ id: string; name: string; depth: number }> = [];
  const walk = (nodes: typeof roots, depth: number) => {
    for (const node of nodes) {
      flatFolders.push({ id: node.id, name: node.name, depth });
      if (node.children.length > 0) walk(node.children, depth + 1);
    }
  };
  walk(roots, 0);

  const createInProject = createDesign.bind(null, projectSlug);

  return (
    <div className="flex min-h-screen flex-col">
      <AppTopBar
        teams={teams}
        activeTeamId={teamId}
        userName={session.user.name}
        userEmail={session.user.email}
        active="designs"
        projectSlug={projectSlug}
        projects={projects}
      />
      <main className="mx-auto flex w-full max-w-5xl flex-col gap-8 p-8">
        <header className="flex items-baseline justify-between">
          <div>
            <h1 className="text-2xl font-semibold tracking-tight">Designs</h1>
            <p className="text-sm text-muted-foreground">
              Mockups in <span className="text-zinc-200">{projectName}</span>{" "}
              — generated by the design agent. Group them into folders by
              flow, surface, or sprint.
            </p>
          </div>
          <form action={createInProject}>
            <Button type="submit">New design</Button>
          </form>
        </header>

        <DesignFolderTree
          roots={roots}
          rootDesigns={rootDesigns}
          hrefBase={`/p/${projectSlug}/designs`}
          projectSlug={projectSlug}
          allFolders={flatFolders}
        />
      </main>
    </div>
  );
}
