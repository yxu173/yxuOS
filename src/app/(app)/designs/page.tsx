import { eq } from "drizzle-orm";

import { Button } from "@/components/ui/button";
import { WorkspaceGrid } from "@/components/workspaces/workspace-grid";
import { WorkspaceTabs } from "@/components/workspaces/workspace-tabs";
import { db } from "@/db";
import { designs } from "@/db/schema";
import { requireActiveTeam } from "@/lib/permissions";

import { createDesign, deleteDesign, renameDesign } from "./actions";

export default async function DesignsIndexPage() {
  const { teamId } = await requireActiveTeam();

  const userDesigns = await db.query.designs.findMany({
    where: eq(designs.teamId, teamId),
    columns: {
      id: true,
      name: true,
      createdAt: true,
      updatedAt: true,
    },
  });

  return (
    <main className="mx-auto flex min-h-screen w-full max-w-5xl flex-col gap-8 p-8">
      <WorkspaceTabs active="designs" />

      <header className="flex items-baseline justify-between">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">Designs</h1>
          <p className="text-sm text-muted-foreground">
            Mockups, landing pages, dashboards — generated by the design agent.
          </p>
        </div>
        <form action={createDesign}>
          <Button type="submit">New design</Button>
        </form>
      </header>

      <WorkspaceGrid
        items={userDesigns}
        hrefBase="/designs"
        itemLabel="design"
        itemLabelPlural="designs"
        emptyHint='Hit "New design" and ask the agent to mock up a landing page.'
        renameAction={renameDesign}
        deleteAction={deleteDesign}
      />
    </main>
  );
}
